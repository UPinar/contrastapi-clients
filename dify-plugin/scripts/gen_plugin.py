        '    zh_Hans: "ContrastAPI"',
        "  description:",
        f"    en_US: {_q(_PROVIDER_DESCRIPTION)}",
        f"    zh_Hans: {_q(_PROVIDER_DESCRIPTION)}",
        '  icon: "logo.png"',
        "  tags:",
        '    - "utilities"',
