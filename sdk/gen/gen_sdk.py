#!/usr/bin/env python3
"""Generate the SDK operation tables from the server's OpenAPI document.

The committed ``sdk/openapi.json`` is the output of ``make -s openapi`` in the
server repository. This script reads it and writes three files.
``sdk/node/src/operations.js`` holds the operation table that the client reads
to build a request. ``sdk/node/src/operations.d.ts`` types the arguments and
the methods. ``sdk/python/contrastapi/_operations.py`` holds the table and the
typed methods.

The script leaves out an operation whose request body is raw bytes
(application/octet-stream), because the clients send JSON bodies only.

Usage: gen_sdk.py [--check] [--root DIR]
"""

import argparse
import json
import keyword
import re
import sys
import textwrap
from pathlib import Path

SOURCE = "sdk/openapi.json"
NODE_JS = "sdk/node/src/operations.js"
NODE_DTS = "sdk/node/src/operations.d.ts"
PYTHON = "sdk/python/contrastapi/_operations.py"
OUTPUTS = (NODE_JS, NODE_DTS, PYTHON)

HEADER = "Generated by sdk/gen/gen_sdk.py from sdk/openapi.json — do not edit."
WRAP_WIDTH = 80
PYTHON_LINE_MAX = 100
SCHEMA_REF_PREFIX = "#/components/schemas/"
RAW_BODY = "application/octet-stream"
JSON_BODY = "application/json"

NODE_CLIENT_MEMBERS = frozenset({"call", "request", "lastRateLimit", "constructor"})
PYTHON_CLIENT_MEMBERS = frozenset({"call", "request", "close", "aclose", "last_rate_limit"})
OBJECT_PROTOTYPE_MEMBERS = frozenset({
    "constructor", "hasOwnProperty", "isPrototypeOf", "propertyIsEnumerable",
    "toLocaleString", "toString", "valueOf", "__proto__", "__defineGetter__",
    "__defineSetter__", "__lookupGetter__", "__lookupSetter__",
})
# THENABLE_MEMBER is the member that makes an object thenable. `await client` calls a
# then() method with two functions. A generated method refuses them, so the await never settles.
THENABLE_MEMBER = "then"
PYTHON_METHOD_LOCALS = frozenset({"self", "args"})
TYPE_NAMES = frozenset({"OperationArgs"})
HTTP_METHODS = {"get": "GET", "post": "POST"}
PARAM_PLACES = frozenset({"path", "query"})
SCHEMA_KEYS = frozenset({
    "type", "enum", "const", "minimum", "maximum", "maxLength", "items", "minItems",
    "maxItems", "description", "default",
})
SCALAR_TYPES = {
    "string": ("string", "str"),
    "integer": ("number", "int"),
    "number": ("number", "float"),
    "boolean": ("boolean", "bool"),
}

_OPERATION_ID = re.compile(r"[a-z][a-z0-9_]*")
_IDENTIFIER = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")
_ITEM_TYPE_NAME = re.compile(r"[A-Z][A-Za-z0-9]*")
_PLACEHOLDER = re.compile(r"\{([^}]*)\}")
_OPERATION_PATH = re.compile(r"/[a-z0-9_]+(/|/\{[a-z_][a-z0-9_]*\})?")


class GenError(Exception):
    """GenError means the document holds a shape that this generator does not know."""


def camel_case(operation_id):
    """camel_case returns the Node method name: cve_lookup becomes cveLookup."""
    first, *rest = operation_id.split("_")
    return first + "".join(part[:1].upper() + part[1:] for part in rest)


def pascal_case(operation_id):
    """pascal_case returns the type-name stem: cve_lookup becomes CveLookup."""
    method_name = camel_case(operation_id)
    return method_name[:1].upper() + method_name[1:]


# _STATED_PRICE matches a description whose last sentence states the price. The server
# writes that sentence for a flat tool that does not cost 1 credit, because it is the
# price that MCP's tools/list shows. The generator does not repeat it.
_STATED_PRICE = re.compile(r"Costs (?:no credits|[0-9]+ credits?)\.$")


def credit_text(cost, per_item):
    """credit_text returns the sentence that tells what one call costs.

    A per-item operation charges 1 credit for each item that the server keeps, and
    never less than x-credit-cost. The server's src/openapi.c says so above
    static_appendOperation.
    """
    if cost == 0:
        return "Free."
    unit = "credit" if cost == 1 else "credits"
    if per_item:
        return f"Costs 1 credit per item, at least {cost} {unit}."
    return f"Costs {cost} {unit}."


def limit_text(schema):
    """limit_text returns the numeric limits of a schema as sentences."""
    parts = []
    if "minimum" in schema:
        parts.append(f"Minimum {schema['minimum']}.")
    if "maximum" in schema:
        parts.append(f"Maximum {schema['maximum']}.")
    if "maxLength" in schema and "enum" not in schema:
        parts.append(f"At most {schema['maxLength']} characters.")
    low, high = schema.get("minItems"), schema.get("maxItems")
    if low is not None and high is not None:
        parts.append(f"{low} to {high} items.")
    elif low is not None:
        parts.append(f"At least {low} items.")
    elif high is not None:
        parts.append(f"At most {high} items.")
    if "default" in schema:
        parts.append(f"Default {schema['default']}.")
    return " ".join(parts)


def param_text(description, schema):
    """param_text joins the description of a parameter and its limits into one text."""
    limits = limit_text(schema)
    if not description:
        return limits
    if not limits:
        return description
    if description[-1] not in ".!?":
        description += "."
    return f"{description} {limits}"


def schema_types(schema, where):
    """schema_types returns the (TypeScript, Python) types of a parameter schema."""
    unknown = set(schema) - SCHEMA_KEYS
    if unknown:
        raise GenError(f"{where}: unknown schema key {sorted(unknown)[0]}")
    kind = schema.get("type")
    if "default" in schema:
        _check_default(schema, where)
    if "const" in schema:
        if kind != "boolean" or schema["const"] is not True:
            raise GenError(f"{where}: only a boolean const true is known")
        return "true", "Literal[True]"
    if "enum" in schema:
        values = schema["enum"]
        if kind != "string" or not values or not all(isinstance(v, str) for v in values):
            raise GenError(f"{where}: only a non-empty string enum is known")
        literals = [json.dumps(value) for value in values]
        return " | ".join(literals), "Literal[" + ", ".join(literals) + "]"
    if kind in SCALAR_TYPES:
        return SCALAR_TYPES[kind]
    if kind == "array":
        items = schema.get("items")
        if items == {"type": "string"}:
            return "string[]", "list[str]"
        ref = items.get("$ref") if isinstance(items, dict) and set(items) == {"$ref"} else None
        if isinstance(ref, str) and ref.startswith(SCHEMA_REF_PREFIX):
            name = ref[len(SCHEMA_REF_PREFIX):]
            if not _ITEM_TYPE_NAME.fullmatch(name) or name in TYPE_NAMES or name.endswith("Args"):
                raise GenError(f"{where}: item type name {name!r} cannot be a client type name")
            return f"{name}[]", f"list[{name}]"
        raise GenError(f"{where}: unknown array items {json.dumps(items)}")
    raise GenError(f"{where}: unknown schema type {kind!r}")


def _check_default(schema, where):
    """_check_default refuses a default that is not an integer inside the schema's limits.

    The server writes a default only for a page size or an offset. The default becomes a
    sentence in the generated text, so a value the server would refuse must not reach it.
    A bool is an int in Python, so the check names it.
    """
    value = schema["default"]
    if schema.get("type") != "integer" or isinstance(value, bool) or not isinstance(value, int):
        raise GenError(f"{where}: only an integer default is known")
    if value < schema.get("minimum", value) or value > schema.get("maximum", value):
        raise GenError(f"{where}: default {value} is outside the limits")


def _check_name(name, where):
    """_check_name refuses a parameter name that one of the clients cannot carry.

    Node reads args[name], so an Object.prototype member would read an inherited value.
    Python mangles a name like __x inside the method class, so the keyword argument of
    the caller would not match it. Python also refuses __debug__ as a parameter. The
    function therefore refuses every name that starts with two underscores.
    """
    if not isinstance(name, str) or not _IDENTIFIER.fullmatch(name):
        raise GenError(f"{where}: parameter name {name!r} is not an identifier")
    if keyword.iskeyword(name) or name in PYTHON_METHOD_LOCALS or name.startswith("__"):
        raise GenError(f"{where}: parameter name {name!r} is taken in Python")
    if name in OBJECT_PROTOTYPE_MEMBERS:
        raise GenError(f"{where}: parameter name {name!r} is an Object.prototype member")


def _param(name, place, required, description, schema, where):
    _check_name(name, where)
    node_type, python_type = schema_types(schema, f"{where}.{name}")
    return {
        "name": name,
        "in": place,
        "required": required is True,
        "text": param_text(description, schema),
        "node_type": node_type,
        "python_type": python_type,
        "item_type": node_type[:-2] if node_type.endswith("[]") and node_type != "string[]" else None,
    }


def _body_params(request_body, where):
    content = request_body.get("content", {})
    if set(content) != {JSON_BODY}:
        raise GenError(f"{where}: unknown request body {sorted(content)}")
    schema = content[JSON_BODY]["schema"]
    if schema.get("type") != "object" or not isinstance(schema.get("properties"), dict):
        raise GenError(f"{where}: request body is not an object")
    required = set(schema.get("required", []))
    return [
        _param(name, "body", name in required, prop.get("description"), prop, where)
        for name, prop in schema["properties"].items()
    ]


def _is_raw_body(operation):
    content = operation.get("requestBody", {}).get("content", {})
    return set(content) == {RAW_BODY}


def load_operations(document):
    """load_operations reads the operations of the document, in document order.

    It raises GenError on a shape that the clients cannot carry.
    """
    if not isinstance(document, dict) or not isinstance(document.get("paths"), dict):
        raise GenError("the document has no paths object")
    operations = []
    method_names = set()
    for path, item in document["paths"].items():
        # Each client appends the path to its base URL, so a path must not change the host.
        if not isinstance(path, str) or not _OPERATION_PATH.fullmatch(path):
            raise GenError(f"{path!r}: the path is not /name, /name/ or /name/{{param}}")
        for http_method, op in item.items():
            if http_method not in HTTP_METHODS:
                raise GenError(f"{path}: unknown HTTP method {http_method}")
            op_id = op.get("operationId")
            if not isinstance(op_id, str) or not _OPERATION_ID.fullmatch(op_id):
                raise GenError(f"{path}: operationId {op_id!r} is not [a-z][a-z0-9_]*")
            if _is_raw_body(op):
                continue
            method_name = camel_case(op_id)
            if keyword.iskeyword(op_id):
                raise GenError(f"{op_id}: the operationId is a Python keyword")
            if method_name in NODE_CLIENT_MEMBERS or method_name in OBJECT_PROTOTYPE_MEMBERS:
                raise GenError(f"{op_id}: method name {method_name} is a Node client member")
            if method_name == THENABLE_MEMBER:
                raise GenError(f"{op_id}: method name {method_name} makes the Node client thenable")
            if op_id in PYTHON_CLIENT_MEMBERS:
                raise GenError(f"{op_id}: method name {op_id} is a Python client member")
            if method_name in method_names:
                raise GenError(f"{op_id}: duplicate method name {method_name}")
            method_names.add(method_name)
            if pascal_case(op_id) + "Args" in TYPE_NAMES:
                raise GenError(f"{op_id}: the args type name is taken")
            params = []
            for raw in op.get("parameters", []):
                if raw.get("in") not in PARAM_PLACES:
                    raise GenError(f"{op_id}: unknown parameter place {raw.get('in')!r}")
                params.append(_param(raw.get("name"), raw["in"], raw.get("required"),
                                     raw.get("description"), raw["schema"], op_id))
            if "requestBody" in op:
                params.extend(_body_params(op["requestBody"], op_id))
            names = [p["name"] for p in params]
            if len(set(names)) != len(names):
                raise GenError(f"{op_id}: two parameters share a name")
            placeholders = set(_PLACEHOLDER.findall(path))
            if placeholders != {p["name"] for p in params if p["in"] == "path"}:
                raise GenError(f"{op_id}: the path placeholders differ from the path parameters")
            cost = op.get("x-credit-cost")
            if type(cost) is not int or cost < 0:
                raise GenError(f"{op_id}: x-credit-cost is not a non-negative integer")
            per_item = op.get("x-credit-cost-per-item", False)
            if type(per_item) is not bool:
                raise GenError(f"{op_id}: x-credit-cost-per-item is not a boolean")
            description = op.get("description")
            states_price = isinstance(description, str) and _STATED_PRICE.search(description)
            paragraphs = [op.get("summary"), description, None if states_price else credit_text(cost, per_item)]
            operations.append({
                "id": op_id,
                "method_name": method_name,
                "type_name": pascal_case(op_id) + "Args",
                "method": HTTP_METHODS[http_method],
                "path": path,
                "params": params,
                "paragraphs": [p for p in paragraphs if p],
            })
    return operations


def item_type_fields(document, name):
    """item_type_fields returns (name, TypeScript type, Python type, required) of each field.

    The item type is the object schema components.schemas.<name> of an array parameter.
    """
    try:
        schema = document["components"]["schemas"][name]
    except (KeyError, TypeError):
        raise GenError(f"{name} is used but components.schemas.{name} is missing")
    properties = schema.get("properties", {})
    required = schema.get("required", [])
    if schema.get("type") != "object" or not set(required) <= set(properties):
        raise GenError(f"{name} must be an object whose required fields are its own fields")
    fields = []
    for field, prop in properties.items():
        _check_name(field, name)
        if prop.get("type") not in SCALAR_TYPES or set(prop) - {"type", "description"}:
            raise GenError(f"{name}.{field}: only a plain scalar field is known")
        fields.append((field, *SCALAR_TYPES[prop["type"]], field in required))
    return fields


def _wrap(text):
    return textwrap.wrap(text, WRAP_WIDTH, break_long_words=False, break_on_hyphens=False)


def _jsdoc(paragraphs, indent):
    """_jsdoc returns a JSDoc block. One paragraph that fits one line stays on one line."""
    blocks = [_wrap(text.replace("*/", "*\\/")) for text in paragraphs]
    if len(blocks) == 1 and len(blocks[0]) == 1:
        return [f"{indent}/** {blocks[0][0]} */"]
    lines = [f"{indent}/**"]
    for index, block in enumerate(blocks):
        if index:
            lines.append(f"{indent} *")
        lines.extend(f"{indent} * {line}" for line in block)
    lines.append(f"{indent} */")
    return lines


def render_node_js(operations):
    lines = [f"// {HEADER}", "export const OPERATIONS = Object.freeze({"]
    for op in operations:
        lines.append(f"  {op['id']}: Object.freeze({{")
        lines.append(f"    methodName: {json.dumps(op['method_name'])},")
        lines.append(f"    method: {json.dumps(op['method'])},")
        lines.append(f"    path: {json.dumps(op['path'])},")
        if op["params"]:
            lines.append("    params: Object.freeze([")
            for p in op["params"]:
                required = "true" if p["required"] else "false"
                lines.append(f"      Object.freeze({{ name: {json.dumps(p['name'])}, "
                             f"in: {json.dumps(p['in'])}, required: {required} }}),")
            lines.append("    ]),")
        else:
            lines.append("    params: Object.freeze([]),")
        lines.append("  }),")
    lines.append("});")
    return "\n".join(lines) + "\n"


def render_node_dts(operations, item_types):
    lines = [
        f"// {HEADER}",
        "",
        "export interface OperationParam {",
        "  readonly name: string;",
        '  readonly in: "path" | "query" | "body";',
        "  readonly required: boolean;",
        "}",
        "",
        "export interface OperationSpec {",
        "  readonly methodName: string;",
        '  readonly method: "GET" | "POST";',
        "  readonly path: string;",
        "  readonly params: readonly OperationParam[];",
        "}",
        "",
    ]
    for type_name, fields in item_types:
        lines.append(f"export interface {type_name} {{")
        lines.extend(f"  {name}{'' if required else '?'}: {node_type};"
                     for name, node_type, _, required in fields)
        lines.extend(["}", ""])
    for op in operations:
        lines.append(f"export interface {op['type_name']} {{")
        if not op["params"]:
            lines.append("  [key: string]: never;")
        for p in op["params"]:
            if p["text"]:
                lines.extend(_jsdoc([p["text"]], "  "))
            optional = "" if p["required"] else "?"
            lines.append(f"  {p['name']}{optional}: {p['node_type']};")
        lines.extend(["}", ""])
    lines.append("export type OperationId =")
    for index, op in enumerate(operations):
        end = ";" if index == len(operations) - 1 else ""
        lines.append(f"  | {json.dumps(op['id'])}{end}")
    lines.extend(["", "export interface OperationArgs {"])
    lines.extend(f"  {op['id']}: {op['type_name']};" for op in operations)
    lines.extend(["}", "", "export interface ContrastAPIMethods {"])
    for op in operations:
        lines.extend(_jsdoc(op["paragraphs"], "  "))
        optional = "" if any(p["required"] for p in op["params"]) else "?"
        lines.append(f"  {op['method_name']}(args{optional}: {op['type_name']}): Promise<unknown>;")
    lines.extend([
        "}",
        "",
        "export declare const OPERATIONS: Readonly<Record<OperationId, OperationSpec>>;",
    ])
    return "\n".join(lines) + "\n"


def _python_doc_escape(text):
    return text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')


def _docstring(op, indent):
    """_docstring returns the method docstring: the JSDoc paragraphs, then Args."""
    paragraphs = [_wrap(_python_doc_escape(text)) for text in op["paragraphs"]]
    documented = [p for p in op["params"] if p["text"]]
    if documented:
        block = ["Args:"]
        for p in documented:
            wrapped = _wrap(f"{p['name']}: {_python_doc_escape(p['text'])}")
            block.append(f"    {wrapped[0]}")
            block.extend(f"        {line}" for line in wrapped[1:])
        paragraphs.append(block)
    lines = []
    for index, block in enumerate(paragraphs):
        if index:
            lines.append("")
        lines.extend(block)
    out = [f'{indent}"""{lines[0]}']
    out.extend(f"{indent}{line}" if line else "" for line in lines[1:])
    out.append(f'{indent}"""')
    return out


def _python_method(op, is_async):
    prefix = "async def" if is_async else "def"
    call = "await self.call" if is_async else "self.call"
    params = [f"{p['name']}: {p['python_type']}" if p["required"]
              else f"{p['name']}: {p['python_type']} | None = None" for p in op["params"]]
    returns = " -> dict[str, Any]:"
    one_line = f"    async def {op['id']}(self{', *, ' if params else ''}{', '.join(params)}){returns}"
    if len(one_line) <= PYTHON_LINE_MAX:
        lines = [f"    {prefix} {op['id']}(self{', *, ' if params else ''}{', '.join(params)}){returns}"]
    else:
        lines = [f"    {prefix} {op['id']}(", "        self,", "        *,"]
        lines.extend(f"        {param}," for param in params)
        lines.append(f"    ){returns}")
    lines.extend(_docstring(op, "        "))
    required = [p for p in op["params"] if p["required"]]
    optional = [p for p in op["params"] if not p["required"]]
    initial = "{" + ", ".join(f"{json.dumps(p['name'])}: {p['name']}" for p in required) + "}"
    if not optional:
        lines.append(f"        return {call}({json.dumps(op['id'])}, {initial})")
        return lines
    lines.append(f"        args: dict[str, Any] = {initial}")
    for p in optional:
        lines.append(f"        if {p['name']} is not None:")
        lines.append(f"            args[{json.dumps(p['name'])}] = {p['name']}")
    lines.append(f"        return {call}({json.dumps(op['id'])}, args)")
    return lines


def _python_item_type(type_name, fields):
    """_python_item_type returns the TypedDict classes of one item type.

    NotRequired needs Python 3.11, and the package supports 3.10. A TypedDict with
    total=False therefore holds the optional fields, and its base class holds the others.
    """
    required = [f"    {name}: {python_type}" for name, _, python_type, is_required in fields if is_required]
    optional = [f"    {name}: {python_type}" for name, _, python_type, is_required in fields if not is_required]
    if not optional:
        return ["", "", f"class {type_name}(TypedDict):", *required]
    if not required:
        return ["", "", f"class {type_name}(TypedDict, total=False):", *optional]
    base = f"_{type_name}Required"
    return ["", "", f"class {base}(TypedDict):", *required,
            "", "", f"class {type_name}({base}, total=False):", *optional]


def render_python(operations, item_types):
    lines = [
        f"# {HEADER}",
        '"""Operation table and typed methods of the ContrastAPI REST API."""',
        "",
        "from __future__ import annotations",
        "",
        "from collections.abc import Mapping",
        "from types import MappingProxyType",
        "from typing import TYPE_CHECKING, Any, Final, Literal, TypedDict",
        "",
        "OPERATIONS: Final[Mapping[str, Mapping[str, Any]]] = MappingProxyType({",
    ]
    for op in operations:
        lines.append(f"    {json.dumps(op['id'])}: {{")
        lines.append(f'        "method_name": {json.dumps(op["id"])},')
        lines.append(f'        "method": {json.dumps(op["method"])},')
        lines.append(f'        "path": {json.dumps(op["path"])},')
        if op["params"]:
            lines.append('        "params": (')
            for p in op["params"]:
                lines.append(f'            {{"name": {json.dumps(p["name"])}, "in": '
                             f'{json.dumps(p["in"])}, "required": {p["required"]}}},')
            lines.append("        ),")
        else:
            lines.append('        "params": (),')
        lines.append("    },")
    lines.append("})")
    for type_name, fields in item_types:
        lines.extend(_python_item_type(type_name, fields))
    for class_name, is_async in (("_SyncMethods", False), ("_AsyncMethods", True)):
        prefix = "async def" if is_async else "def"
        lines.extend([
            "",
            "",
            f"class {class_name}:",
            "    if TYPE_CHECKING:",
            f"        {prefix} call(self, operation_id: str, "
            "args: Mapping[str, Any] | None = None) -> Any: ...",
        ])
        for op in operations:
            lines.append("")
            lines.extend(_python_method(op, is_async))
    return "\n".join(lines) + "\n"


def render_outputs(document):
    """render_outputs returns {relative path: text} of every generated file."""
    operations = load_operations(document)
    used = sorted({p["item_type"] for op in operations for p in op["params"] if p["item_type"]})
    item_types = [(name, item_type_fields(document, name)) for name in used]
    return {
        NODE_JS: render_node_js(operations),
        NODE_DTS: render_node_dts(operations, item_types),
        PYTHON: render_python(operations, item_types),
    }


def _read(path):
    with open(path, encoding="utf-8", newline="") as handle:
        return handle.read()


def _write(path, text):
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


def main(argv=None):
    """main rewrites the generated files. With --check it only reports.

    It returns 0 when nothing changes or after a rewrite. It returns 1 when
    --check finds a file that would change or is missing. It returns 2 on
    unusable input.
    """
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="exit 1 if a file would change; write nothing")
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2],
                        help="clients repository root (default: two levels above sdk/gen)")
    args = parser.parse_args(argv)

    try:
        document = json.loads(_read(args.root / SOURCE))
        outputs = render_outputs(document)
    except (OSError, ValueError, KeyError, TypeError, AttributeError, GenError) as exc:
        print(f"gen_sdk: {exc}", file=sys.stderr)
        return 2

    changed = []
    for relpath, text in outputs.items():
        path = args.root / relpath
        if not path.exists():
            changed.append((relpath, "missing"))
        elif _read(path) != text:
            changed.append((relpath, "would change"))

    if args.check:
        for relpath, state in changed:
            print(f"{relpath}: {state}")
        return 1 if changed else 0

    for relpath, _ in changed:
        _write(args.root / relpath, outputs[relpath])
    return 0


if __name__ == "__main__":
    sys.exit(main())
