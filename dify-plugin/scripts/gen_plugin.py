_YAML_LINE_BREAKS = ("\u0085", "\u2028", "\u2029")
# _OPERATION_PATH is the path shape the server writes: one word, then at most one placeholder.
_OPERATION_PATH = re.compile(r"/[a-z0-9_]+(/|/\{[a-z_][a-z0-9_]*\})?")

