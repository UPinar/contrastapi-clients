                       {"type": "integer", "default": 1.5}, {"type": "string", "default": "x"},
                       {"type": "integer", "minimum": 1, "default": 0},
                       {"type": "integer", "minimum": "1", "default": 5}, {"type": "integer", "minimum": "x"},
                       {"type": "integer", "maximum": True}, {"type": "integer", "minimum": 1.0},
