def _render(doc):
    return gen.render_outputs(copy.deepcopy(doc))


def _one_param(schema, description=None):
    """_one_param returns an op entry with one optional parameter a: a body field for an array."""
    if schema.get("type") == "array":
        prop = dict(schema, description=description) if description else schema
        return ("/x", "post", _op("x", body=({"a": prop}, [])))
    return ("/x", "get", _op("x", params=[_param("a", schema, description=description)]))


def _render_one(*ops, schemas=None):
    """Render a document of ops (each (path, method, op)); return (js, dts, py)."""
    out = _render(_doc(*ops, schemas=schemas))
    return out[gen.NODE_JS], out[gen.NODE_DTS], out[gen.PYTHON]


def _lines(text):
    return text.split("\n")


class _RootCase(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name)
        for relpath in gen.OUTPUTS:
            (self.root / relpath).parent.mkdir(parents=True, exist_ok=True)
        self.write_doc(FIXTURE)

    def tearDown(self):
        self.tmp.cleanup()

    def write_doc(self, doc):
        (self.root / "sdk" / "openapi.json").write_text(json.dumps(doc), encoding="utf-8")

    def run_main(self, *args):
        stdout = io.StringIO()
        with contextlib.redirect_stdout(stdout), contextlib.redirect_stderr(io.StringIO()):
            code = gen.main([*args, "--root", str(self.root)])
        return code, stdout.getvalue()

    def snapshot(self):
        return {relpath: (self.root / relpath).read_bytes() if (self.root / relpath).exists()
                else None for relpath in gen.OUTPUTS}


