#!/usr/bin/env python3
"""Generate the Dify plugin's tool files from the server's OpenAPI document.

The committed ``sdk/openapi.json`` is the output of ``make -s openapi`` in the
server repository. Each operation that carries ``tags`` is an MCP tool, and
each such tool but the ones in EXCLUDED_TOOLS becomes a Dify tool. The script
writes ``provider/contrastapi.yaml``, ``tools/_ops.py``, one ``tools/<id>.yaml``
and one ``tools/<id>.py`` per tool, and the tool section of ``README.md``.

The script needs no YAML library. Every text from the document is written as
a JSON string. YAML would fold three line-break characters inside such a string
(U+0085, U+2028, U+2029), so _q writes them as escapes.

Usage: gen_plugin.py [--check] [--root DIR]
"""

