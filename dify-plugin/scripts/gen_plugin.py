# there is generated, so --check reports one that no tool writes any more.
_HAND_TOOL_FILES = frozenset({"tools/__init__.py", "tools/_api.py"})

_HTTP_METHODS = {"get": "GET", "post": "POST"}
_SCHEMA_REF_PREFIX = "#/components/schemas/"
_JSON_BODY = "application/json"

# _STATED_PRICE matches a description whose last sentence already states the price.
# gen_sdk.py uses the same rule, so the price sentence is not written twice.
_STATED_PRICE = re.compile(r"Costs (?:no credits|[0-9]+ credits?)\.$")


class GenError(Exception):
    """GenError means the document holds a shape that this generator does not know."""


def _resolve(schema, document):
    """Return schema with an array's ``$ref`` items replaced by the component schema."""
    items = schema.get("items")
    if not isinstance(items, dict) or "$ref" not in items:
        return schema
    ref = items["$ref"]
    if not isinstance(ref, str) or not ref.startswith(_SCHEMA_REF_PREFIX):
        raise GenError(f"unknown $ref {ref!r}")
    try:
        target = document["components"]["schemas"][ref[len(_SCHEMA_REF_PREFIX):]]
    except (KeyError, TypeError) as exc:
        raise GenError(f"{ref} is missing") from exc
    return {**schema, "items": target}


def _make_param(name, place, required, description, schema, document, where):
    if not isinstance(name, str) or not name:
        raise GenError(f"{where}: a parameter has no name")
    if not isinstance(schema, dict):
        raise GenError(f"{where}.{name}: the parameter has no schema")
    text = description or PARAM_TEXT_FALLBACK.get(name)
    if not text:
        raise GenError(f"{where}.{name}: no description and no fallback text")
    resolved = _resolve(schema, document)
    return {
        "name": name,
        "place": place,
        "required": required is True,
        "schema": resolved,
        "text": param_text(text, resolved),
    }


def _operation_params(op, document, where):
    params = []
    for raw in op.get("parameters", []):
        place = raw.get("in")
        if place not in ("path", "query"):
            raise GenError(f"{where}: unknown parameter place {place!r}")
        params.append(_make_param(raw.get("name"), place, raw.get("required"),
                                  raw.get("description"), raw.get("schema"), document, where))
    body = op.get("requestBody")
    if body is not None:
        content = body.get("content", {})
        if set(content) != {_JSON_BODY}:
            raise GenError(f"{where}: unknown request body {sorted(content)}")
        schema = content[_JSON_BODY].get("schema", {})
        properties = schema.get("properties")
        if schema.get("type") != "object" or not isinstance(properties, dict):
            raise GenError(f"{where}: request body is not an object")
        required = set(schema.get("required", []))
        for name, prop in properties.items():
            params.append(_make_param(name, "body", name in required,
                                      prop.get("description"), prop, document, where))
    return params


def load_tools(document):
    """Return one dict per tagged operation that is not excluded, sorted by id.

    Raises GenError when the document has no paths object, when an operationId
    or a path has another shape, when a tool's method is not GET or POST, when
    x-credit-cost is not a non-negative integer, when a parameter has no text,
    when an excluded name is missing from the document, or when two operations
    share an operationId. The path check keeps a path from changing the host.
    """
    if not isinstance(document, dict) or not isinstance(document.get("paths"), dict):
        raise GenError("the document has no paths object")
    tools = []
    seen = set()
    for path, item in document["paths"].items():
        for http_method, op in item.items():
            if not isinstance(op, dict) or not op.get("tags"):
                continue
            op_id = op.get("operationId")
            if not isinstance(op_id, str) or not re.fullmatch(r"[a-z][a-z0-9_]*", op_id):
                raise GenError(f"{path}: operationId {op_id!r} is not [a-z][a-z0-9_]*")
            seen.add(op_id)
            if op_id in EXCLUDED_TOOLS:
                continue
            if not isinstance(path, str) or not _OPERATION_PATH.fullmatch(path):
                raise GenError(f"{op_id}: path {path!r} has another shape")
            if http_method not in _HTTP_METHODS:
                raise GenError(f"{op_id}: unknown HTTP method {http_method}")
            cost = op.get("x-credit-cost")
            if type(cost) is not int or cost < 0:
                raise GenError(f"{op_id}: x-credit-cost is not a non-negative integer")
            tools.append({
                "id": op_id,
                "method": _HTTP_METHODS[http_method],
                "path": path,
                "title": op.get("summary") or op_id,
                "description": op.get("description") or "",
                "category": op["tags"][0],
                "credit": credit_text(cost, op.get("x-credit-cost-per-item", False) is True),
                "params": _operation_params(op, document, op_id),
            })
    missing = EXCLUDED_TOOLS - seen
    if missing:
        raise GenError(f"excluded tool {sorted(missing)[0]} is not in the document")
    ids = [tool["id"] for tool in tools]
    if len(set(ids)) != len(ids):
        raise GenError("two operations share an operationId")
    return sorted(tools, key=lambda tool: tool["id"])


def dify_type(schema):
    """Return the Dify parameter type of a schema."""
    if "enum" in schema:
        return "select"
    kind = schema.get("type")
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    return "string"


def label_text(name):
    """Return the form label of a parameter name: "cve_ids" becomes "CVE IDs"."""
    words = [LABEL_WORDS.get(word, word[:1].upper() + word[1:]) for word in name.split("_") if word]
    return " ".join(words)


def _op_kind(schema):
    """Return the kind that tools/_api.py reads to convert one argument."""
    kind = schema.get("type")
    if kind == "boolean":
        return "const_true" if schema.get("const") is True else "boolean"
    if kind in ("integer", "number"):
        return kind
    if kind == "array":
        items = schema.get("items") or {}
        if items.get("type") == "object":
            return "object_array"
        if items.get("type") == "string":
            return "string_array"
        raise GenError(f"unknown array items {json.dumps(items)}")
    return "string"


def _q(text):
    quoted = json.dumps(text, ensure_ascii=False)
    for char in _YAML_LINE_BREAKS:
        quoted = quoted.replace(char, f"\\u{ord(char):04x}")
    return quoted


def _llm_text(tool):
    description = tool["description"]
    if not description:
        return tool["credit"]
    if _STATED_PRICE.search(description):
        return description
    return f"{description} {tool['credit']}"


def _param_lines(name, kind, required, label, text, schema=None):
    lines = [
        f"  - name: {_q(name)}",
        f"    type: {kind}",
        f"    required: {'true' if required else 'false'}",
        "    label:",
        f"      en_US: {_q(label)}",
        "    human_description:",
        f"      en_US: {_q(text)}",
        f"    llm_description: {_q(text)}",
        "    form: llm",
    ]
    if schema is None:
        return lines
    if kind == "select":
        lines.append("    options:")
        for value in schema["enum"]:
            lines.append(f"      - value: {_q(str(value))}")
            lines.append("        label:")
            lines.append(f"          en_US: {_q(str(value))}")
    if "default" in schema and kind == "number":
        lines.append(f"    default: {json.dumps(schema['default'])}")
    elif "default" in schema and kind == "select":
        lines.append(f"    default: {_q(str(schema['default']))}")
    return lines


def _param_text_with_hint(param):
    schema = param["schema"]
    if schema.get("type") != "array":
        return param["text"]
    if _op_kind(schema) == "object_array":
        return param["text"] + _OBJECT_ARRAY_HINT
    return param["text"] + _STRING_ARRAY_HINT


def render_tool_yaml(tool):
    """Return the Dify tool yaml of one tool."""
    if tool["id"] == PASSWORD_TOOL:
        human = _PASSWORD_HUMAN
        llm = f"{_PASSWORD_HUMAN} {_PASSWORD_LOG_SENTENCE} {tool['credit']}"
        param_blocks = [_param_lines("password", "secret-input", True, "Password", _PASSWORD_PARAM_TEXT)]
    else:
        human = first_sentence(tool["description"]) if tool["description"] else tool["title"]
        llm = _llm_text(tool)
        param_blocks = [
            _param_lines(param["name"], dify_type(param["schema"]), param["required"],
                         label_text(param["name"]), _param_text_with_hint(param), param["schema"])
            for param in tool["params"]
        ]
    lines = [
        "identity:",
        f"  name: {_q(tool['id'])}",
        f"  author: {_q(AUTHOR)}",
        "  label:",
        f"    en_US: {_q(tool['title'])}",
        "description:",
        "  human:",
        f"    en_US: {_q(human)}",
        f"  llm: {_q(llm)}",
    ]
    if param_blocks:
        lines.append("parameters:")
        for block in param_blocks:
            lines.extend(block)
    else:
        lines.append("parameters: []")
    lines += [
        "extra:",
        "  python:",
        f"    source: {_q('tools/' + tool['id'] + '.py')}",
    ]
    return "\n".join(lines) + "\n"


def _pascal_case(op_id):
    return "".join(part[:1].upper() + part[1:] for part in op_id.split("_"))


def render_tool_py(tool):
    """Return the Dify tool class of one tool. It hands the call to tools/_api.py."""
    return (
        f'"""{_GENERATED_HEADER}"""\n'
        "from collections.abc import Generator\n"
        "from typing import Any\n"
        "\n"
        "from dify_plugin import Tool\n"
        "from dify_plugin.entities.tool import ToolInvokeMessage\n"
        "\n"
        "from tools._api import invoke_operation\n"
        "\n"
        "\n"
        f"class {_pascal_case(tool['id'])}Tool(Tool):\n"
        "    def _invoke(self, tool_parameters: dict[str, Any]) -> Generator[ToolInvokeMessage, None, None]:\n"
        f"        yield from invoke_operation(self, {_q(tool['id'])}, tool_parameters)\n"
    )


